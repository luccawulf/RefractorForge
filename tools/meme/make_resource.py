r"""make_resource.py - writes src/RefractorForge.Formats/Menu/MemeSchema.json, the class table the C# Meme library
(RefractorForge.Formats.Menu) embeds, from meme_schema.json (the full table with every angle's provenance).

    python tools/meme/make_resource.py

It keeps what an editor needs, per game and class: the short and full class name, the base class, the payload
tokens with their engine labels, and per field the base class an O slot asks for, the handle kind of an s8 (texture,
font, sound), whether the O is the node's "Next node" (its sibling, not a child), the enum names (tables shared by
several fields are stored once), and the engine constraint (BfVerticalScrollExNode Version == 1); per class whether
real data proves the layout or only the engine does, the three deprecated classes, whether it is a file object at all
(System and Ref2System are runtime roots), and the engine serialize address for provenance; plus the Tree node
layouts.  Re-run it whenever meme_schema.json changes; the C# tests read the result.
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'meme_schema.json')
DST = os.path.normpath(os.path.join(HERE, '..', '..', 'src', 'RefractorForge.Formats', 'Menu', 'MemeSchema.json'))

GAMES = (('BF1942', 'Bf1942', 'BF1942.exe'), ('BFV', 'Bfv', 'BfVietnam.exe'))

# The engine logs a deprecation warning when it loads one of these (BF1942 strings 0x00940A50 / 0x00942D30 /
# 0x009420A8); the load slot then reads the normal payload.  An editor should not offer them for new objects.
DEPRECATED = {
    'CullActionNode': 'deprecated: the engine logs a warning when it loads one (BF1942 string 0x00940A50); its '
                      'Event type / Event data fields are marked OBS, DO NOT USE',
    'SetVariableSinusAction': 'deprecated: "should be replaced with SetVariableSineAction" (BF1942 string 0x00942D30)',
    'ShowEffectNode': 'deprecated: "use TransitionalEffectNode instead" (BF1942 string 0x009420A8)',
}

# Registered under another namespace than dice::meme:: (never written into a file).
FULL_NAMES = {'Ref2System': 'dice::ref2::menu::Ref2System'}

# What the two NavigateTreeObject slots hold (spec 5.3: [O Description (Data), O Action]).
NODE_EXPECTS = {'Description': 'Data', 'Action': 'Action'}


def enum_key(frm):
    # 'BfVietnam.exe 0x00878550; the same name strings ...' -> '0x00878550'
    return frm.split(';')[0].split()[-1]


def main():
    S = json.load(open(SRC))
    enums = {}
    out = {
        'about': 'Generated by tools/meme/make_resource.py from tools/meme/meme_schema.json; do not edit by hand. '
                 'The spec is docs/Meme_Format.md.',
        'enums': enums,
        'treeNodes': {},
        'games': {},
    }
    for node, toks in S['_tree']['node_layouts'].items():
        out['treeNodes'][node] = [{'tok': t, 'label': l, 'expects': NODE_EXPECTS.get(l)} for t, l in toks]
    for key, game, exe in GAMES:
        classes = []
        note = None
        for name in sorted(S[key]):
            c = S[key][name]
            src = c.get('source') or {}
            eng = src.get('engine')
            status = src.get('status', '')
            cls = {
                'name': name,
                'full': FULL_NAMES.get(name, 'dice::meme::' + name),
                'base': c.get('base'),
                'status': status,
                'proven': 'proven by' in status,
            }
            if isinstance(eng, dict):
                cls['va'] = eng['serialize']
                cls['engine'] = '%s serialize %s, vtable %s, %s' % (eng['exe'], eng['serialize'], eng['vtable'],
                                                                   eng['serialize_slot'])
            else:
                cls['engine'] = eng
            if name in DEPRECATED:
                cls['deprecated'] = DEPRECATED[name]
            if src.get('not_a_file_object'):
                cls['notAFileObject'] = src['not_a_file_object']
            fields = []
            metas = c.get('fields') or [{}] * len(c['tokens'])
            assert len(metas) == len(c['tokens']), name
            labels = [l for t, l in c['tokens']]
            assert len(labels) == len(set(labels)), 'duplicate labels in %s' % name
            for i, ((tok, label), meta) in enumerate(zip(c['tokens'], metas)):
                f = {'tok': tok, 'label': label}
                if meta.get('slot'):
                    f['slot'] = meta['slot']
                ex = meta.get('expects')
                if ex:
                    f['expects'] = ex.split()[0]          # 'Object (list items; ...)' -> 'Object'
                if meta.get('handle'):
                    f['handle'] = meta['handle']
                if meta.get('role', '').startswith('sibling'):
                    assert i == 0 and tok == 'O' and label == 'Next node', (name, i, label)
                    f['next'] = True
                if meta.get('enum'):
                    k = enum_key(meta['enum']['from'])
                    names = {int(v): n for v, n in meta['enum']['names'].items()}
                    if k in enums:
                        assert enums[k]['names'] == {str(v): n for v, n in sorted(names.items())}, k
                    else:
                        enums[k] = {'from': meta['enum']['from'].split(';')[0],
                                    'names': {str(v): n for v, n in sorted(names.items())}}
                    f['enum'] = k
                    if ';' in meta['enum']['from']:
                        note = meta['enum']['from'].split(';', 1)[1].strip()
                eq = (meta.get('constraint') or {}).get('eq')
                if eq is not None:
                    f['mustEqual'] = eq
                    f['why'] = meta['constraint'].get('why')
                if meta.get('node'):
                    f['treeNode'] = meta['node']
                fields.append(f)
            cls['fields'] = fields
            classes.append(cls)
        g = {'exe': exe, 'classes': classes}
        if note:
            g['enumNote'] = 'enum names from BfVietnam.exe; ' + note
        out['games'][game] = g
    os.makedirs(os.path.dirname(DST), exist_ok=True)
    # one class per line: small, and a schema change shows up as a readable diff
    c = lambda o: json.dumps(o, ensure_ascii=True, separators=(',', ':'))
    lines = ['{', ' "about":%s,' % c(out['about']), ' "enums":{']
    lines += ['  %s:%s%s' % (c(k), c(v), ',' if i < len(enums) - 1 else '') for i, (k, v) in enumerate(enums.items())]
    lines += [' },', ' "treeNodes":%s,' % c(out['treeNodes']), ' "games":{']
    for gi, (game, g) in enumerate(out['games'].items()):
        head = {k: v for k, v in g.items() if k != 'classes'}
        lines.append('  %s:{%s,"classes":[' % (c(game), c(head)[1:-1]))
        lines += ['   %s%s' % (c(x), ',' if i < len(g['classes']) - 1 else '') for i, x in enumerate(g['classes'])]
        lines.append('  ]}%s' % (',' if gi < len(out['games']) - 1 else ''))
    lines += [' }', '}', '']
    text = '\n'.join(lines)
    assert json.loads(text) == out
    with open(DST, 'w', newline='\n') as fh:
        fh.write(text)
    print('wrote %s: %s' % (DST, ', '.join('%s %d classes' % (g, len(v['classes'])) for g, v in out['games'].items())))
    return 0


if __name__ == '__main__':
    sys.exit(main())
